'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const root = process.cwd();
const errors = [];

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(root, relativePath), 'utf8'));
}

function addError(message) {
  errors.push(message);
}

const packageJson = readJson('package.json');
const expectedWorkspaces = ['apps/*', 'packages/*'];

if (packageJson.private !== true) {
  addError('root package.json must remain private');
}

if (packageJson.type !== 'module') {
  addError('root package.json must use ESM via "type": "module"');
}

if (packageJson.engines?.node !== '22.x') {
  addError('root package.json must pin the Node runtime policy to 22.x');
}

if (JSON.stringify(packageJson.workspaces) !== JSON.stringify(expectedWorkspaces)) {
  addError('root npm workspaces must be exactly apps/* and packages/* during the foundation phase');
}

if (fs.readFileSync(path.join(root, '.nvmrc'), 'utf8').trim() !== '22') {
  addError('.nvmrc must target Node 22');
}

if (!fs.existsSync(path.join(root, 'package-lock.json'))) {
  addError('package-lock.json is required and must be generated by npm before commit');
}

for (const forbiddenLockfile of ['pnpm-lock.yaml', 'pnpm-workspace.yaml', 'yarn.lock']) {
  if (fs.existsSync(path.join(root, forbiddenLockfile))) {
    addError(`forbidden package-manager artifact found: ${forbiddenLockfile}`);
  }
}

let trackedFiles = [];
try {
  trackedFiles = execFileSync('git', ['ls-files'], { cwd: root, encoding: 'utf8' })
    .split(/\r?\n/)
    .map((value) => value.trim())
    .filter(Boolean);
} catch (error) {
  addError(`unable to inspect tracked files with git ls-files: ${String(error)}`);
}

const secretPatterns = [
  /(^|\/)\.env$/u,
  /(^|\/)\.env\.(?!example$)[^/]+$/u,
  /service-account.*\.json$/iu,
  /firebase-adminsdk-.*\.json$/iu,
  /google-application-credentials.*\.json$/iu,
];

for (const trackedFile of trackedFiles) {
  const normalized = trackedFile.replaceAll('\\', '/');

  if (secretPatterns.some((pattern) => pattern.test(normalized))) {
    addError(`credential/environment file must not be tracked: ${normalized}`);
  }

  if (/^(apps|packages)\/.+\.(?:js|jsx|cjs|mjs)$/u.test(normalized)) {
    addError(`first-party application/workspace source must use .ts/.tsx, found: ${normalized}`);
  }
}

if (errors.length > 0) {
  console.error('[repo-policy] FAILED');
  for (const error of errors) {
    console.error(`  - ${error}`);
  }
  process.exit(1);
}

console.log('[repo-policy] OK — npm workspace, runtime, lockfile, source-extension, and secret policies hold.');
